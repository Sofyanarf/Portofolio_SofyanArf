export function initEnglishTasks() {
  const openButtons = document.querySelectorAll('.open-task-btn');
  const taskModal = document.getElementById('task-modal');
  const taskModalClose = document.getElementById('task-modal-close-btn');

  if (!taskModal) return;

  openButtons.forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const taskId = btn.getAttribute('data-task-id');
      openTaskModal(taskId);
    });
  });

  if (taskModalClose) {
    taskModalClose.addEventListener('click', () => {
      taskModal.classList.remove('open');
    });
  }

  taskModal.addEventListener('click', (e) => {
    if (e.target === taskModal) {
      taskModal.classList.remove('open');
    }
  });
}

export function openTaskModal(taskId) {
  const task = englishTasksData.find(t => t.id === taskId);
  const taskModal = document.getElementById('task-modal');
  const modalContent = document.getElementById('task-modal-content');

  if (!task || !taskModal || !modalContent) return;

  modalContent.innerHTML = `
    <div class="task-modal-detail">
      <!-- Modal Header -->
      <div class="task-modal-header-badge">
        <span class="task-modal-num">${task.num}</span>
        <div>
          <span class="task-modal-type-tag"><i class="${task.typeIcon}"></i> ${task.type}</span>
          <h2 class="task-modal-title">${task.title}</h2>
          <p class="task-modal-sub">${task.subtitle}</p>
        </div>
      </div>

      <!-- Overview Box -->
      <div class="task-modal-box">
        <h4><i class="fa-solid fa-circle-info"></i> Deskripsi & Ringkasan Tugas</h4>
        <p>${task.fullDescription}</p>
      </div>

      <!-- Quick Metrics Grid -->
      <div class="task-modal-metrics">
        ${task.taskHighlights.map(item => `
          <div class="task-metric-item">
            <span class="metric-label">${item.label}</span>
            <strong class="metric-value">${item.val}</strong>
          </div>
        `).join('')}
      </div>

      <!-- Learning Outcomes -->
      <div class="task-modal-box">
        <h4><i class="fa-solid fa-bullseye"></i> Capaian & Kompetensi Bahasa (Learning Outcomes)</h4>
        <ul class="task-modal-list">
          ${task.learningOutcomes.map(item => `
            <li><i class="fa-solid fa-check"></i> ${item}</li>
          `).join('')}
        </ul>
      </div>

      <!-- Tags & Actions -->
      <div class="task-modal-footer">
        <div class="task-modal-tags">
          ${task.tags.map(t => `<span class="task-tag">[${t}]</span>`).join('')}
        </div>
        <div class="task-modal-actions">
          ${task.driveUrl ? `
            <a href="${task.driveUrl}" target="_blank" rel="noopener noreferrer" class="btn btn-primary btn-sm">
              <i class="fa-brands fa-google-drive"></i> Buka Google Drive ↗
            </a>
          ` : ''}
          <button class="btn btn-outline btn-sm" id="btn-copy-task-info">
            <i class="fa-solid fa-copy"></i> Salin Ringkasan
          </button>
          <button class="btn btn-outline btn-sm" id="btn-close-task-modal">
            <i class="fa-solid fa-check"></i> Selesai
          </button>
        </div>
      </div>
    </div>
  `;

  // Attach close button inside modal
  const innerCloseBtn = document.getElementById('btn-close-task-modal');
  if (innerCloseBtn) {
    innerCloseBtn.addEventListener('click', () => {
      taskModal.classList.remove('open');
    });
  }

  // Attach copy button
  const copyBtn = document.getElementById('btn-copy-task-info');
  if (copyBtn) {
    copyBtn.addEventListener('click', () => {
      const summaryText = `${task.title}\n${task.subtitle}\n\n${task.fullDescription}`;
      navigator.clipboard.writeText(summaryText).then(() => {
        const toast = document.createElement('div');
        toast.className = 'toast toast-success';
        toast.innerHTML = `<i class="fa-solid fa-check"></i> <span>Ringkasan tugas berhasil disalin ke clipboard!</span>`;
        const container = document.getElementById('toast-container');
        if (container) {
          container.appendChild(toast);
          setTimeout(() => toast.remove(), 3000);
        }
      });
    });
  }

  taskModal.classList.add('open');
}

